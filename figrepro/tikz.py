# -*- coding: utf-8 -*-
"""
figrepro.tikz -- 把同一份 :class:`figrepro.canvas.Figure` 描述输出成 TikZ 源码。

坐标直接沿用原图像素，靠 ``x=K mm, y=-K mm`` 翻转 y 轴，因此 .tex 里的数字
和原图逐像素对得上，可以直接拿原图量。

两个已知的 TikZ 坑，这里已经绕开：

* ``dash pattern`` 必须通过 ``\\tikzset`` 定义成 style 使用；把宏直接展开到
  draw 选项里会报 ``\\tikz@scandashon doesn't match its definition``。
* 节点锚点用 ``base`` / ``base west`` / ``base east``：y 轴翻转后 north/south
  之类会跟着翻，而基线锚点在翻转下不变，配合"给基线坐标"的约定最稳。
"""

from __future__ import annotations

import os

TEMPLATE = r"""%% !TEX program = xelatex
%% =====================================================================
%%  Generated by figrepro -- do not edit by hand, edit the Figure spec.
%%  Source canvas: %(w_px)d x %(h_px)d px   ->   %(w_mm).2f mm wide
%%  Compile with xelatex (fontspec is required).
%% =====================================================================
\documentclass[tikz,border=%(border)gpt]{standalone}
\usepackage{fontspec}
\setmainfont{%(latin_font)s}
%(cjk_line)s\usepackage{graphicx}
\usepackage{tikz}
\usetikzlibrary{calc}
%(color_defs)s
%(dash_defs)s
\begin{document}
\begin{tikzpicture}[x=%(k).6fmm, y=-%(k).6fmm, line cap=butt, line join=miter,
                   every node/.style={inner sep=0pt, outer sep=0pt}]
%(body)s
\end{tikzpicture}
\end{document}
"""


class TikzBackend:
    """把 :class:`figrepro.canvas.Figure` 写成独立可编译的 TikZ 文档。"""

    def __init__(self, fig, latin_font="Times New Roman", cjk_font=None,
                 border=0):
        self.f = fig
        self.latin_font = latin_font
        self.cjk_font = cjk_font
        self.border = border

    def pt(self, px):
        return self.f.pt(px)

    def mm(self, px):
        return self.f.mm_per_px * px

    # ------------------------------------------------------------------ 生成
    def source(self):
        f = self.f
        body, color_defs, dash_defs = [], [], []
        color_names = {}

        def cname(col):
            """返回 TikZ 颜色名，顺带登记 \\definecolor。

            三种情况：'#RRGGBB' 直接定义；调色板名查表定义；
            其余（white/black 等 xcolor 预定义名）原样透传。
            """
            if not col or col == "none":
                return "none"
            if col in color_names:
                return color_names[col]
            if col.startswith("#"):
                nm, hexv = "c%d" % len(color_names), col
            elif col in f.colors:
                nm, hexv = col, f.colors[col]
            else:
                color_names[col] = col        # 预定义名，不需要 definecolor
                return col
            color_names[col] = nm
            color_defs.append(r"\definecolor{%s}{HTML}{%s}"
                              % (nm, hexv.lstrip("#").upper()))
            return nm

        for col in list(f.colors):
            cname(col)

        # 每个不同的虚线节奏登记一个 style
        dash_styles = {}
        for it in f.items:
            d = it.get("dash")
            if d:
                key = (round(d[0], 4), round(d[1], 4))
                if key not in dash_styles:
                    nm = "fdash%d" % len(dash_styles)
                    dash_styles[key] = nm
                    dash_defs.append(
                        r"\tikzset{%s/.style={dash pattern=on %.5gpt off %.5gpt}}"
                        % (nm, self.pt(key[0]), self.pt(key[1])))

        for it in sorted(f.items, key=lambda d: d.get("z", 5)):
            body.extend(self._emit(it, cname, dash_styles))

        defs_txt = "\n".join(color_defs)
        dash_txt = "\n".join(dash_defs)
        cjk_line = ""
        if self.cjk_font:
            cjk_line = ("\\setCJKmainfont{%s}[AutoFakeBold=2.5]\n"
                        % self.cjk_font)
        return TEMPLATE % dict(
            w_px=int(f.width_px), h_px=int(f.height_px), w_mm=f.width_mm,
            k=f.mm_per_px, border=self.border, latin_font=self.latin_font,
            cjk_line=cjk_line,
            color_defs=defs_txt, dash_defs=dash_txt, body="\n".join(body))

    def _emit(self, it, cname, dash_styles):
        k = it["kind"]
        out = []
        if k == "rect":
            h = it["lw"] / 2.0                 # 坐标是外沿 -> 路径内缩半线宽
            x0, y0, x1, y1 = (it["x0"] + h, it["y0"] + h,
                              it["x1"] - h, it["y1"] - h)
            r = max(it["rc"] - h, 0.0)
            opts = ["fill=%s" % cname(it["fill"]), "draw=black",
                    "line width=%.5gpt" % self.pt(it["lw"])]
            if r > 0:
                opts.append("rounded corners=%.5gmm" % self.mm(r))
            if it["dash"]:
                opts.append(dash_styles[(round(it["dash"][0], 4),
                                         round(it["dash"][1], 4))])
            out.append(r"\draw[%s] (%.4g,%.4g) rectangle (%.4g,%.4g);"
                       % (", ".join(opts), x0, y0, x1, y1))
        elif k == "line":
            pts = " -- ".join("(%.4g,%.4g)" % p for p in it["pts"])
            out.append(r"\draw[line width=%.5gpt] %s;" % (self.pt(it["lw"]), pts))
        elif k == "poly":
            pts = " -- ".join("(%.4g,%.4g)" % p for p in it["pts"])
            if it["lw"]:
                out.append(r"\draw[fill=%s, draw=black, line width=%.5gpt] "
                           r"%s -- cycle;"
                           % (cname(it["fill"]), self.pt(it["lw"]), pts))
            else:
                out.append(r"\fill %s -- cycle;" % pts)
        elif k == "bezier":
            # matplotlib 的 codes 约定：连续三个 'C' 构成一段三次贝塞尔曲线
            pts, seg, i, j = it["pts"], [], 0, 0
            codes = it["codes"]
            while j < len(codes):
                c = codes[j]
                if c == "M":
                    seg.append("(%.4g,%.4g)" % pts[i]); i += 1; j += 1
                elif c == "L":
                    seg.append("-- (%.4g,%.4g)" % pts[i]); i += 1; j += 1
                else:                                       # 'C'
                    seg.append(".. controls (%.4g,%.4g) and (%.4g,%.4g) .. (%.4g,%.4g)"
                               % (pts[i][0], pts[i][1], pts[i + 1][0],
                                  pts[i + 1][1], pts[i + 2][0], pts[i + 2][1]))
                    i += 3; j += 3
            out.append(r"\draw[line width=%.5gpt] %s;" %
                       (self.pt(it["lw"]), " ".join(seg)))
        elif k == "text":
            size = self.pt(it["size_px"])
            cmd = ""
            if it["weight"] == "bold":
                cmd += r"\bfseries"
            if it["style"] == "italic":
                cmd += r"\itshape"
            anchor = {"w": "base west", "c": "base", "e": "base east"}[it["anchor"]]
            out.append(r"\node[anchor=%s] at (%.4g,%.4g) "
                       r"{\fontsize{%.3gpt}{%.3gpt}\selectfont %s %s};"
                       % (anchor, it["x"], it["y"], size, size * 1.15,
                          cmd, it["s"]))
        elif k == "circle":
            if it["lw"]:
                out.append(r"\draw[fill=%s, draw=black, line width=%.5gpt] "
                           r"(%.4g,%.4g) circle (%.4gmm);"
                           % (cname(it["fill"]), self.pt(it["lw"]),
                              it["cx"], it["cy"], self.mm(it["r"])))
            else:
                out.append(r"\fill (%.4g,%.4g) circle (%.4gmm);"
                           % (it["cx"], it["cy"], self.mm(it["r"])))
        elif k == "image":
            cx = (it["x0"] + it["x1"]) / 2.0
            cy = (it["y0"] + it["y1"]) / 2.0
            out.append(r"\node at (%.4g,%.4g) {\includegraphics[width=%.4gmm,"
                       r"height=%.4gmm]{%s}};"
                       % (cx, cy, self.mm(it["x1"] - it["x0"]),
                          self.mm(it["y1"] - it["y0"]),
                          os.path.basename(it["path"])))
        return out

    def save(self, path, latin_font=None, cjk_font=None, border=None):
        if latin_font is not None:
            self.latin_font = latin_font
        if cjk_font is not None:
            self.cjk_font = cjk_font
        if border is not None:
            self.border = border
        d = os.path.dirname(os.path.abspath(path))
        os.makedirs(d, exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(self.source())
        return path
